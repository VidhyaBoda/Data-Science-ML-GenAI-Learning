"""12 - Decoding controls"""

print("Temperature")
print("- Controls the sharpness/randomness of token sampling.")
print("- Lower values generally make output more focused.")
print("- Higher values generally allow more variation.")

print("\nTop-k")
print("- Restricts sampling to the k most probable candidate tokens.")

print("\nTop-p (nucleus sampling)")
print("- Restricts sampling to the smallest candidate set whose cumulative probability")
print("  reaches a chosen probability threshold.")

print("\nImportant:")
print("Exact parameter behavior and supported settings depend on the model/provider.")
